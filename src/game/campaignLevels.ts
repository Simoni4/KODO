// Helper to construct a 9x9 3D matrix of tiles from ASCII art:
// ' ' = 0 (Void / Abyss)
// '.' = 1 (Elevation 0 — Base Snow Ground)
// '#' = 2 (Elevation 1 — +1 Block Up Terrace)
// '^' = 3 (Elevation 2 — +2 Blocks Up Ridge)
// '*' = 4 (Elevation 3 — +3 Blocks Up Summit)
export function makeGrid(rows: string[]): number[][] {
  return rows.map((row) =>
    row.split('').map((ch) => {
      if (ch === '.') return 1; // Elevation 0
      if (ch === '#') return 2; // Elevation 1 (+1 block up)
      if (ch === '^') return 3; // Elevation 2 (+2 blocks up)
      if (ch === '*') return 4; // Elevation 3 (+3 blocks up)
      return 0; // ' ' = Void
    })
  );
}

